#!/usr/bin/env python3
"""Build and safely install Bind9 split-horizon views for Personal KVM.

The internal view serves PRIVATE_DOMAIN and EXTERNAL_DOMAIN. The public view
serves only EXTERNAL_DOMAIN. DNS recursion is disabled; public queries do not
leak private zone content.
"""
import argparse
import ipaddress
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

LABEL=re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?$")
def domain(s):
    if not isinstance(s,str) or len(s)>253 or not s or not all(LABEL.fullmatch(x) for x in s.rstrip(".").split(".")):
        raise ValueError("Invalid zone name")
    return s.rstrip(".").lower()

def render(private, external, reverse, internal, management, server):
    private,external,reverse=map(domain,(private,external,reverse))
    if private==external or not reverse.endswith(".in-addr.arpa"):
        raise ValueError("Private/external zones must differ; reverse requires in-addr.arpa")
    internal=ipaddress.ip_network(internal,strict=True)
    management=ipaddress.ip_network(management,strict=True)
    ipaddress.ip_address(server)
    if internal.version!=4 or management.version!=4:
        raise ValueError("Only IPv4 networks currently supported")
    for net in (internal,management):
        if not net.is_private: raise ValueError("Internal view must not include public subnets")
    # Files were created and checked by setup_bind9.sh, and owned by named.
    return f'''// Generated by Personal KVM. Keep private data outside the public view.
options {{
    directory "/var/named";
    listen-on port 53 {{ any; }};
    listen-on-v6 {{ none; }};
    allow-query {{ any; }};
    recursion no;
    dnssec-validation auto;
}};
include "/etc/named/pkvm/pkvm-ddns.key";
acl pkvm_private {{ 127.0.0.1; {internal.with_prefixlen}; {management.with_prefixlen}; }};
view "private" {{
    match-clients {{ pkvm_private; }};
    recursion no;
    zone "{private}" IN {{ type master; file "/var/named/pkvm/{private}.zone";
       update-policy {{ grant pkvm-ddns zonesub A; grant pkvm-ddns zonesub AAAA; }}; allow-transfer {{ none; }}; }};
    zone "{reverse}" IN {{ type master; file "/var/named/pkvm/{reverse}.zone";
       update-policy {{ grant pkvm-ddns zonesub PTR; }}; allow-transfer {{ none; }}; }};
    zone "{external}" IN {{ type master; file "/var/named/pkvm/external-internal.zone"; allow-update {{ none; }}; }};
}};
view "public" {{
    match-clients {{ any; }};
    recursion no;
    zone "{external}" IN {{ type master; file "/var/named/pkvm/external-public.zone"; allow-update {{ none; }}; }};
}};
'''

def install(args):
    configuration=render(args.private,args.external,args.reverse,args.internal,args.management,args.server)
    if os.geteuid()!=0: raise PermissionError("Root required")
    conf=Path("/etc/named.conf")
    if not conf.is_file(): raise FileNotFoundError(conf)
    root=Path("/var/named/pkvm")
    root.mkdir(mode=0o750,parents=True,exist_ok=True)
    for kind in ("external-internal","external-public"):
        path=root/(kind+".zone")
        if not path.exists():
            path.write_text(f'$TTL 300\n@ IN SOA ns1.{args.external}. hostmaster.{args.external}. ( 1 3600 900 604800 300 )\n@ IN NS ns1.{args.external}.\n',encoding="utf-8")
            shutil.chown(path,user="named",group="named")
            path.chmod(0o640)
    original=conf.read_bytes()
    backup=conf.with_name("named.conf.pkvm-before-views")
    if not backup.exists():
        backup.write_bytes(original)
        backup.chmod(0o600)
    fd,candidate=tempfile.mkstemp(prefix=".named.pkvm-",dir=str(conf.parent))
    try:
        with os.fdopen(fd,"w",encoding="utf-8") as stream:
            stream.write(configuration)
        subprocess.run(["named-checkconf","-z",candidate],check=True,timeout=20)
        os.chmod(candidate,0o640)
        shutil.chown(candidate,user="root",group="named")
        os.replace(candidate,conf)
        try:
            subprocess.run(["systemctl","restart","named.service"],check=True,timeout=35)
        except Exception:
            # Restore exact previous bytes and restart before reporting failure.
            conf.write_bytes(original)
            subprocess.run(["systemctl","restart","named.service"],check=False,timeout=35)
            raise
    finally:
        if os.path.exists(candidate): os.unlink(candidate)

def main():
    p=argparse.ArgumentParser()
    for name in ("private","external","reverse","internal","management","server"):
        p.add_argument("--"+name,required=True)
    p.add_argument("--apply",action="store_true")
    args=p.parse_args()
    try:
        result=render(args.private,args.external,args.reverse,args.internal,args.management,args.server)
        if args.apply: install(args)
        else: print(result)
    except (ValueError,PermissionError,OSError,subprocess.SubprocessError) as exc:
        print("Split DNS configuration failed:",str(exc),file=sys.stderr)
        return 1
    return 0
if __name__=="__main__":
    sys.exit(main())
